    {
        $policies = [
            [
                'title' => 'Политика конфиденциальности',
                'slug' => 'privacy-policy',
                'content' => $this->getPrivacyPolicyContent(),
                'is_active' => true,
            ],
            [
                'title' => 'Условия использования',
                'slug' => 'terms-of-use',
                'content' => $this->getTermsOfUseContent(),
                'is_active' => true,
            ],
            [
                'title' => 'Политика обработки персональных данных',
                'slug' => 'personal-data-policy',
                'content' => $this->getPersonalDataPolicyContent(),
                'is_active' => true,
            ],
            [
                'title' => 'Пользовательское соглашение',
                'slug' => 'user-agreement',
                'content' => $this->getUserAgreementContent(),
                'is_active' => false,
            ],
        ];

        foreach ($policies as $policy) {
            // Проверяем существует ли уже такая политика по slug
            $existing = DB::table('policies')->where('slug', $policy['slug'])->first();

            if (!$existing) {
                DB::table('policies')->insert([
                    'id' => Str::uuid(),
                    'title' => $policy['title'],
                    'slug' => $policy['slug'],
                    'content' => $policy['content'],
                    'is_active' => $policy['is_active'],
                    'created_at' => now(),
                    'updated_at' => now(),
                ]);
            }
        }
    }

